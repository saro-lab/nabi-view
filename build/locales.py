#!/usr/bin/env python3
"""Generate the Rust locale registry and native supported-language declarations."""
import argparse
import json
import plistlib
import re
import subprocess
from pathlib import Path
ROOT = Path(__file__).resolve().parent.parent


def read_catalog(path):
    def unique(pairs):
        result = {}
        for key, value in pairs:
            if key in result:
                raise ValueError(f"Duplicate translation ID in {path.name}: {key}")
            result[key] = value
        return result
    return json.loads(path.read_text(encoding='utf-8'), object_pairs_hook=unique)


def validate(entries):
    if len({item['code'] for item in entries}) != len(entries):
        raise ValueError('Duplicate locale code')
    english = read_catalog(ROOT / 'locales/en.json')
    for item in entries:
        if item['direction'] not in ('rtl', 'ltr'):
            raise ValueError(f"Invalid direction: {item['code']}")
        translated = read_catalog(ROOT / f"locales/{item['code']}.json")
        if translated.keys() != english.keys():
            raise ValueError(f"Missing or extra IDs in {item['code']}")
        for key, value in translated.items():
            if not isinstance(value, str) or not value.strip():
                raise ValueError(f"Empty translation: {item['code']}/{key}")
            if sorted(re.findall(r'{([^{}]+)}', value)) != sorted(re.findall(r'{([^{}]+)}', english[key])):
                raise ValueError(f"Mismatched parameters: {item['code']}/{key}")


def generated():
    entries = json.loads((ROOT / 'locales/manifest.json').read_text(encoding='utf-8'))
    validate(entries)
    source = '''// Generated by build/locales.py from locales/manifest.json.
use serde::{Deserialize, Deserializer, Serialize, Serializer};
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub enum Language {
    #[default]
    System,
'''
    source += ''.join(f'    {item["variant"]},\n' for item in entries)
    source += '    Other(String),\n}\nimpl Language {\n'
    source += '    pub const ALL: &[Self] = &[Self::System, ' + ', '.join('Self::' + e['variant'] for e in entries) + '];\n'
    for name, field, system in [('code', 'code', '"system"'), ('native_name', 'name', 'super::tr("system")')]:
        source += f'    pub fn {name}(&self) -> &str {{ match self {{ Self::System => {system},\n'
        source += ''.join(f'        Self::{e["variant"]} => {json.dumps(e[field], ensure_ascii=False)},\n' for e in entries)
        source += '        Self::Other(code) => code,\n    } }\n'
    source += '    pub fn from_code(code: &str) -> Self { match code { "system" => Self::System,\n'
    source += ''.join(f'        "{e["code"]}" => Self::{e["variant"]},\n' for e in entries)
    source += '        code => Self::Other(code.to_owned()),\n    }}\n'
    source += '    pub fn is_rtl(&self) -> bool { matches!(self, ' + ' | '.join('Self::' + e['variant'] for e in entries if e['direction'] == 'rtl') + ') }\n}\n'
    source += '''impl Serialize for Language {
    fn serialize<S: Serializer>(&self, serializer: S) -> Result<S::Ok, S::Error> { serializer.serialize_str(self.code()) }
}
impl<'de> Deserialize<'de> for Language {
    fn deserialize<D: Deserializer<'de>>(deserializer: D) -> Result<Self, D::Error> {
        Ok(Self::from_code(&String::deserialize(deserializer)?))
    }
}
'''
    def rustfmt(text):
        return subprocess.run(['rustfmt', '--edition', '2024'], input=text, text=True, capture_output=True, check=True).stdout.encode()
    yield ROOT / 'src/i18n/language.rs', rustfmt(source)
    catalogs = '// Generated by build/locales.py. Catalogs are embedded for offline use.\n'
    catalogs += 'pub(super) const SOURCES: &[&str] = &[\n' + ''.join(f'    include_str!(concat!(env!("CARGO_MANIFEST_DIR"), "/locales/{e["code"]}.json")),\n' for e in entries) + '];\n'
    yield ROOT / 'src/i18n/catalogs.rs', rustfmt(catalogs)
    for name in ['macos', 'ios']:
        path = ROOT / f'platforms/{name}/Info.plist'
        data = plistlib.loads(path.read_bytes())
        data['CFBundleDevelopmentRegion'] = 'en'
        data['CFBundleLocalizations'] = [e['code'] for e in entries]
        yield path, plistlib.dumps(data, sort_keys=False)
    xml = '<?xml version="1.0" encoding="utf-8"?>\n<locale-config xmlns:android="http://schemas.android.com/apk/res/android">\n'
    xml += ''.join(f'    <locale android:name="{e["code"]}" />\n' for e in entries) + '</locale-config>\n'
    yield ROOT / 'platforms/android/app/src/main/res/xml/locales_config.xml', xml.encode()


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for path, data in generated():
        if args.check:
            if not path.exists() or path.read_bytes() != data:
                raise SystemExit(f'Outdated locale declaration: {path.relative_to(ROOT)}')
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
